_TAB_TITLES = {path: label for path, _area, label in PAGES}


def about_key(doc_id: str) -> str:
    """id документа → ключ ABOUT (все вкладки WB описаны одним текстом)."""
    return 'weld_balance' if doc_id.startswith('weld_balance_') else doc_id


def about(doc_id: str) -> dict | None:
    """Пояснение к документу для баннера: ссылки на вкладки — с их названиями на сайте."""
    a = ABOUT.get(about_key(doc_id))
    if not a:
        return None
    return {**{k: v for k, v in a.items() if k != 'feeds'},
            'feeds': [{'href': href, 'tab': _TAB_TITLES.get(href, href), 'what': what}
                      for href, what in a['feeds']]}


def site_map(docs: dict) -> list[dict]:
    """«Карта данных»: для каждой вкладки сайта — какие документы её питают и чем.

    docs — результат documents.get_documents(). Порядок — по группам (эталон → справочники →
    записи → настройки); вкладки WB сведены в один пункт «Weld Balance» со списком моделей."""
    by_key = {}                                    # ключ ABOUT → [(doc_id, title)] в порядке docs
    for doc_id, cfg in docs.items():
        if about_key(doc_id) in ABOUT:
            by_key.setdefault(about_key(doc_id), []).append({'doc': doc_id, 'title': cfg['title']})
    group_pos = {g[0]: i for i, g in enumerate(GROUPS)}
    keys = sorted(by_key, key=lambda k: group_pos[ABOUT[k]['group']])
    out = []
    for href in SITE_TABS:
        items = [{'docs': by_key[k], 'doc_title': 'Weld Balance' if k == 'weld_balance' else by_key[k][0]['title'],
                  'what': what}
                 for k in keys for f_href, what in ABOUT[k]['feeds'] if f_href == href]
        if items:
            out.append({'href': href, 'tab': _TAB_TITLES.get(href, href), 'items': items})
    return out
